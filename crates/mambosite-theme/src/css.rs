use std::fmt::Write as _;

use crate::model::{
    ColorPalette, ColorScheme, HeaderMode, Responsive, SidebarMode, TextStyle, Theme,
};

#[derive(Clone, Copy)]
enum Point {
    Compact,
    Content,
    Wide,
}

pub(crate) fn render(theme: &Theme) -> String {
    let mut css = String::from("/* Generated by MamboSite. Do not edit. */\n\n");
    for face in &theme.fonts.faces {
        writeln!(css, "@font-face {{").unwrap();
        writeln!(css, "  font-family: \"{}\";", quoted(&face.family)).unwrap();
        writeln!(
            css,
            "  src: url(\"{}\") format(\"{}\");",
            quoted(&face.source),
            face.format.as_css()
        )
        .unwrap();
        writeln!(css, "  font-weight: {};", face.weight).unwrap();
        writeln!(css, "  font-style: {};", face.style.as_css()).unwrap();
        writeln!(css, "  font-display: {};", face.display.as_css()).unwrap();
        writeln!(css, "}}\n").unwrap();
    }

    let default_palette = palette(theme, theme.default_scheme);
    writeln!(
        css,
        ":root,\n[data-theme=\"{}\"] {{",
        theme.default_scheme.as_str()
    )
    .unwrap();
    write_palette(&mut css, theme.default_scheme, default_palette);
    writeln!(css, "}}\n").unwrap();

    for scheme in [ColorScheme::Dark, ColorScheme::Light] {
        if scheme == theme.default_scheme {
            continue;
        }
        writeln!(css, "[data-theme=\"{}\"] {{", scheme.as_str()).unwrap();
        write_palette(&mut css, scheme, palette(theme, scheme));
        writeln!(css, "}}\n").unwrap();
    }

    writeln!(css, ":root {{").unwrap();
    write_base_tokens(&mut css, theme);
    writeln!(css, "}}\n").unwrap();

    for (point, width) in [
        (Point::Compact, theme.breakpoints.compact),
        (Point::Content, theme.breakpoints.content),
        (Point::Wide, theme.breakpoints.wide),
    ] {
        let declarations = responsive_declarations(theme, point);
        if declarations.is_empty() {
            continue;
        }
        writeln!(css, "@media (min-width: {width}px) {{").unwrap();
        writeln!(css, "  :root {{").unwrap();
        for (name, value) in declarations {
            writeln!(css, "    --mambo-{name}: {value};").unwrap();
        }
        writeln!(css, "  }}").unwrap();
        writeln!(css, "}}\n").unwrap();
    }

    css
}

fn palette(theme: &Theme, scheme: ColorScheme) -> &ColorPalette {
    match scheme {
        ColorScheme::Dark => &theme.colors.dark,
        ColorScheme::Light => &theme.colors.light,
    }
}

fn write_palette(css: &mut String, scheme: ColorScheme, palette: &ColorPalette) {
    writeln!(css, "  color-scheme: {};", scheme.as_str()).unwrap();
    for (name, value) in [
        ("background", &palette.background),
        ("surface", &palette.surface),
        ("surface-strong", &palette.surface_strong),
        ("border", &palette.border),
        ("text", &palette.text),
        ("text-muted", &palette.text_muted),
        ("text-subtle", &palette.text_subtle),
        ("brand", &palette.brand),
        ("brand-hover", &palette.brand_hover),
        ("on-brand", &palette.on_brand),
        ("selection", &palette.selection),
        ("focus", &palette.focus),
        ("success", &palette.success),
        ("warning", &palette.warning),
        ("danger", &palette.danger),
        ("header-background", &palette.header_background),
        ("shadow", &palette.shadow),
    ] {
        writeln!(css, "  --mambo-color-{name}: {value};").unwrap();
    }
    for (index, accent) in palette.accents.iter().enumerate() {
        writeln!(css, "  --mambo-color-accent-{}: {accent};", index + 1).unwrap();
    }
}

fn write_base_tokens(css: &mut String, theme: &Theme) {
    for (name, value) in [
        ("font-body", theme.fonts.body.as_str()),
        ("font-heading", theme.fonts.heading.as_str()),
        ("font-mono", theme.fonts.mono.as_str()),
    ] {
        declaration(css, name, value);
    }

    for (name, style) in typography(theme) {
        declaration(css, &format!("type-{name}-size"), style.size.base());
        declaration(css, &format!("type-{name}-line-height"), &style.line_height);
        declaration(css, &format!("type-{name}-weight"), style.weight);
        declaration(
            css,
            &format!("type-{name}-letter-spacing"),
            &style.letter_spacing,
        );
    }

    for (name, value) in [
        ("space-xxs", &theme.spacing.xxs),
        ("space-xs", &theme.spacing.xs),
        ("space-sm", &theme.spacing.sm),
        ("space-md", &theme.spacing.md),
        ("space-lg", &theme.spacing.lg),
        ("space-xl", &theme.spacing.xl),
        ("space-xxl", &theme.spacing.xxl),
        ("space-section", &theme.spacing.section),
        ("width-reading", &theme.widths.reading),
        ("width-normal", &theme.widths.normal),
        ("width-wide", &theme.widths.wide),
        ("width-full", &theme.widths.full),
        ("width-shell", &theme.widths.shell),
        ("width-sidebar", &theme.widths.sidebar),
        ("width-card-min", &theme.widths.card_min),
        ("width-hero-image-min", &theme.widths.hero_image_min),
        (
            "dimension-main-top-padding",
            theme.dimensions.main_top_padding.base(),
        ),
        (
            "dimension-header-height",
            theme.dimensions.header_height.base(),
        ),
        ("dimension-header-blur", &theme.dimensions.header_blur),
        ("dimension-toc-offset", theme.dimensions.toc_offset.base()),
        (
            "dimension-hero-min-height",
            &theme.dimensions.hero_min_height,
        ),
        (
            "dimension-control-min-height",
            &theme.dimensions.control_min_height,
        ),
        ("border-thin", &theme.borders.thin),
        ("border-strong", &theme.borders.strong),
        ("border-accent", &theme.borders.accent),
        ("radius-small", &theme.radii.small),
        ("radius-medium", &theme.radii.medium),
        ("radius-large", &theme.radii.large),
        ("radius-pill", &theme.radii.pill),
        ("shadow-small", &theme.shadows.small),
        ("shadow-medium", &theme.shadows.medium),
        ("shadow-large", &theme.shadows.large),
        ("motion-fast", &theme.motion.fast),
        ("motion-normal", &theme.motion.normal),
        ("motion-slow", &theme.motion.slow),
        ("motion-easing", &theme.motion.easing),
    ] {
        declaration(css, name, value);
    }
    declaration(css, "border-style", theme.borders.style.as_css());

    declaration(
        css,
        "collection-max-columns",
        theme.components.collection.max_columns.base(),
    );
    write_sidebar(css, *theme.components.sidebar.mode.base());
    write_header_mode(css, *theme.components.header.mode.base());
    declaration(
        css,
        "header-clock-display",
        theme.components.header.clock.base().flex_display(),
    );
    declaration(
        css,
        "header-hide-on-scroll",
        u8::from(theme.components.header.hide_on_scroll),
    );
    declaration(css, "header-hide-after", theme.components.header.hide_after);
}

fn responsive_declarations(theme: &Theme, point: Point) -> Vec<(String, String)> {
    let mut declarations = Vec::new();
    for (name, style) in typography(theme) {
        push_override(
            &mut declarations,
            format!("type-{name}-size"),
            &style.size,
            point,
            ToString::to_string,
        );
    }
    for (name, value) in [
        (
            "dimension-main-top-padding",
            &theme.dimensions.main_top_padding,
        ),
        ("dimension-header-height", &theme.dimensions.header_height),
        ("dimension-toc-offset", &theme.dimensions.toc_offset),
    ] {
        push_override(
            &mut declarations,
            name.to_owned(),
            value,
            point,
            ToString::to_string,
        );
    }
    push_override(
        &mut declarations,
        "collection-max-columns".to_owned(),
        &theme.components.collection.max_columns,
        point,
        ToString::to_string,
    );
    if let Some(mode) = at(&theme.components.sidebar.mode, point) {
        declarations.push(("sidebar-display".to_owned(), mode.display().to_owned()));
        declarations.push(("sidebar-position".to_owned(), mode.position().to_owned()));
    }
    if let Some(mode) = at(&theme.components.header.mode, point) {
        declarations.push(("header-display".to_owned(), mode.display().to_owned()));
        declarations.push(("header-grid-template".to_owned(), mode.columns().to_owned()));
    }
    if let Some(visibility) = at(&theme.components.header.clock, point) {
        declarations.push((
            "header-clock-display".to_owned(),
            visibility.flex_display().to_owned(),
        ));
    }
    declarations
}

fn typography(theme: &Theme) -> [(&'static str, &TextStyle); 9] {
    [
        ("body", &theme.typography.body),
        ("small", &theme.typography.small),
        ("label", &theme.typography.label),
        ("navigation", &theme.typography.navigation),
        ("heading-1", &theme.typography.heading_1),
        ("heading-2", &theme.typography.heading_2),
        ("heading-3", &theme.typography.heading_3),
        ("hero-lead", &theme.typography.hero_lead),
        ("card-title", &theme.typography.card_title),
    ]
}

fn write_sidebar(css: &mut String, mode: SidebarMode) {
    declaration(css, "sidebar-display", mode.display());
    declaration(css, "sidebar-position", mode.position());
}

fn write_header_mode(css: &mut String, mode: HeaderMode) {
    declaration(css, "header-display", mode.display());
    declaration(css, "header-grid-template", mode.columns());
}

fn declaration(css: &mut String, name: &str, value: impl std::fmt::Display) {
    writeln!(css, "  --mambo-{name}: {value};").unwrap();
}

fn push_override<T>(
    output: &mut Vec<(String, String)>,
    name: String,
    responsive: &Responsive<T>,
    point: Point,
    render: impl FnOnce(&T) -> String,
) {
    if let Some(value) = at(responsive, point) {
        output.push((name, render(value)));
    }
}

const fn at<T>(responsive: &Responsive<T>, point: Point) -> Option<&T> {
    match point {
        Point::Compact => responsive.compact(),
        Point::Content => responsive.content(),
        Point::Wide => responsive.wide(),
    }
}

fn quoted(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}
